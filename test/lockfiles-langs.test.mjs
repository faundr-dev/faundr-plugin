test('.NET: packages.lock.json e .csproj', () => {
  const lock = parseLangLockfile('packages.lock.json', JSON.stringify({ version: 1, dependencies: { 'net8.0': { 'Newtonsoft.Json': { type: 'Direct', resolved: '12.0.1' }, App: { type: 'Project' } } } }))
  assert.deepEqual(names(lock), ['Newtonsoft.Json@12.0.1'])
  const proj = parseLangLockfile('src/App.csproj', `<Project Sdk="Microsoft.NET.Sdk">
  <ItemGroup>
    <PackageReference Include="Newtonsoft.Json" Version="12.0.1" />
    <PackageReference Include="Serilog"><Version>2.10.0</Version></PackageReference>
    <PackageReference Include="Floating" Version="*" />
  </ItemGroup>
</Project>`)
  assert.equal(proj.ecosystem, 'NuGet')
  assert.deepEqual(names(proj), ['Newtonsoft.Json@12.0.1', 'Serilog@2.10.0'])
})

test('Maven: pom.xml com propriedades e escopo de teste', () => {
  const r = parseLangLockfile('pom.xml', `<project>
  <groupId>com.app</groupId><artifactId>app</artifactId><version>1.0</version>
  <properties><log4j.version>2.14.1</log4j.version></properties>
  <dependencies>
    <dependency><groupId>org.apache.logging.log4j</groupId><artifactId>log4j-core</artifactId><version>\${log4j.version}</version></dependency>
    <dependency><groupId>junit</groupId><artifactId>junit</artifactId><version>4.12</version><scope>test</scope></dependency>
    <dependency><groupId>org.x</groupId><artifactId>sem-versao</artifactId></dependency>
  </dependencies>
</project>`)
  assert.equal(r.ecosystem, 'Maven')
  assert.deepEqual(names(r), ['org.apache.logging.log4j:log4j-core@2.14.1', 'junit:junit@4.12 (dev)'])
})

test('Gradle: lockfile, build.gradle e catálogo de versões', () => {
  assert.deepEqual(names(parseLangLockfile('gradle.lockfile', 'com.google.code.gson:gson:2.8.5=compileClasspath,runtimeClasspath\njunit:junit:4.12=testCompileClasspath\nempty=')), [
    'com.google.code.gson:gson@2.8.5',
    'junit:junit@4.12 (dev)',
  ])
  assert.deepEqual(names(parseLangLockfile('app/build.gradle.kts', `dependencies {
    implementation("com.squareup.okhttp3:okhttp:3.12.0")
    testImplementation("junit:junit:4.12")
    implementation(libs.androidx.core)
}`)), ['com.squareup.okhttp3:okhttp@3.12.0', 'junit:junit@4.12 (dev)'])
  assert.deepEqual(names(parseLangLockfile('gradle/libs.versions.toml', `[versions]
okhttp = "3.12.0"

[libraries]
okhttp = { module = "com.squareup.okhttp3:okhttp", version.ref = "okhttp" }
gson = { group = "com.google.code.gson", name = "gson", version = "2.8.5" }
`)), ['com.squareup.okhttp3:okhttp@3.12.0', 'com.google.code.gson:gson@2.8.5'])
})

test('Conan: conan.lock', () => {
  const r = parseLangLockfile('conan.lock', JSON.stringify({ version: '0.5', requires: ['zlib/1.2.11#abc%1700000000.0'], build_requires: ['cmake/3.27.0'] }))
  assert.equal(r.ecosystem, 'ConanCenter')
  assert.deepEqual(names(r), ['zlib@1.2.11', 'cmake@3.27.0 (dev)'])
})

test('o manifesto sai da lista quando a pasta tem o lockfile', () => {
  const files = ['app/build.gradle', 'app/gradle.lockfile', 'lib/build.gradle', 'src/App.csproj', 'Cargo.lock', 'README.md'].filter((f) => LANG_LOCKFILE.test(f))
  assert.deepEqual(preferLocks(files), ['app/gradle.lockfile', 'lib/build.gradle', 'src/App.csproj', 'Cargo.lock'])
})
